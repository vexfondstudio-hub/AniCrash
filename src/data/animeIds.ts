export function getAniLibriaId(shikimoriId: string | number): number | null {
  const idStr = String(shikimoriId);
  return ANILIBRIA_ID_MAP[idStr] || null;
}

export function getShikimoriId(titleOrId?: string, englishTitle?: string, poster?: string): number | null {
  if (!titleOrId) return null;
  if (/^\d+$/.test(titleOrId)) {
    return parseInt(titleOrId, 10);
  }
  if (poster) {
    const m = poster.match(/original\/(\d+)\.jpg/);
    if (m) return parseInt(m[1], 10);
  }
  if (ANIME_SHIKIMORI_MAP[titleOrId]) {
    return ANIME_SHIKIMORI_MAP[titleOrId];
  }
  if (englishTitle && ANIME_SHIKIMORI_MAP[englishTitle]) {
    return ANIME_SHIKIMORI_MAP[englishTitle];
  }
  // Loose search
  const lower = titleOrId.toLowerCase();
  for (const [key, id] of Object.entries(ANIME_SHIKIMORI_MAP)) {
    const kLower = key.toLowerCase();
    if (lower.includes(kLower) || kLower.includes(lower)) {
      return id;
    }
  }
  return null;
}
